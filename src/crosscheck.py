def require(needle: str, label: str) -> None:
    if needle not in ALL:
        errors.append(f"не найдено: {label}: {needle}")


def forbid(needle: str, label: str) -> None:
    if needle in ALL:
        errors.append(f"остаточное противоречие: {label}: {needle}")


def table_require(ti: int, needle: str, label: str) -> None:
    # Kept for compatibility with older calls; table numbering can change when
    # a new appendix/table is inserted, so the active checks below use anchors.
    table_text = "\n".join(c[3] for c in cells if c[0] == ti)
    if needle not in table_text:
        errors.append(f"таблица {ti + 1}: {label}: {needle}")

def table_require_anchor(anchor: str, needle: str, label: str) -> None:
    matches=[]
    for ti in sorted({c[0] for c in cells}):
        table_text = "\n".join(c[3] for c in cells if c[0] == ti)
        if anchor in table_text:
            matches.append((ti, table_text))
    if not matches:
        errors.append(f"не найдена таблица-якорь: {label}: {anchor}")
    elif not any(needle in table_text for _, table_text in matches):
        errors.append(f"таблица с якорем «{anchor}»: {label}: {needle}")

