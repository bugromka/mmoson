def p(text, bold=False, italic=False, size=None, align=None, space_after=None):
    par = doc.add_paragraph()
    run = par.add_run(text)
    run.bold, run.italic = bold, italic
    if size:
        run.font.size = Pt(size)
    if align:
        par.alignment = align
    if space_after is not None:
        par.paragraph_format.space_after = Pt(space_after)
    return par


def h(text, level=1):
    return doc.add_heading(text, level=level)


def bullet(text):
    par = doc.add_paragraph(text, style='List Bullet')
    par.paragraph_format.space_after = Pt(3)
    return par


def table(header, rows, widths=None, caption=None, font=9.5):
    if caption:
        cap = doc.add_paragraph()
        r = cap.add_run(caption)
        r.bold = True
        r.font.size = Pt(9.5)
        cap.paragraph_format.space_before = Pt(8)
        cap.paragraph_format.space_after = Pt(3)
        cap.paragraph_format.keep_with_next = True
    t = doc.add_table(rows=1, cols=len(header))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, txt in enumerate(header):
        hdr[i].text = ''
        run = hdr[i].paragraphs[0].add_run(str(txt))
        run.bold = True
        run.font.size = Pt(font)
        hdr[i].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        shd = OxmlElement('w:shd')
        shd.set(qn('w:fill'), 'DEEAF6')
        hdr[i]._tc.get_or_add_tcPr().append(shd)
    for row in rows:
        cells = t.add_row().cells
        for i, txt in enumerate(row):
            cells[i].text = ''
            run = cells[i].paragraphs[0].add_run(str(txt))
            run.font.size = Pt(font)
            if i > 0:
                cells[i].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
    if widths:
        for r_ in t.rows:
            for i, w in enumerate(widths):
                r_.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


